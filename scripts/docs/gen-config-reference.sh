#!/usr/bin/env bash
# Write docs/reference/config-keys.md from config.conf.template (#205).
# Usage: gen-config-reference.sh [--check] [TEMPLATE] [OUTPUT]

set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
check=0
# --check writes nothing and exits 1 if the page is stale.
if [[ "${1:-}" == "--check" ]]; then
  check=1
  shift
fi
template="${1:-${repo}/config/config.conf.template}"
output="${2:-${repo}/docs/reference/config-keys.md}"

[[ -r "${template}" ]] || {
  echo "gen-config-reference: cannot read ${template}" >&2
  exit 2
}

# Tab-separated records: S section, I intro, K key default description.
rows="$(awk '
  # A part that starts lowercase continues the line; others get \001 (<br>).
  function add(d, t) { return d == "" ? t : d (t ~ /^[a-z(]/ ? " " : "\001") t }
  function flush() { if (key != "") print "K\t" key "\t" val "\t" desc; key = "" }
  # A section prints only once it has a key, so the file header is dropped.
  function open_section() { if (sec != "") { print "S\t" sec; if (intro_txt != "") print "I\t" intro_txt }; sec = "" }
  BEGIN { fresh = 1 }
  /^[[:space:]]*$/ { flush(); pending = ""; fresh = 1; next }
  # After a blank line a comment names a section; until a key, its intro.
  # Between keys, a comment describes the key below it.
  /^#/ {
    flush()
    t = $0; sub(/^#[[:space:]]?/, "", t)
    if (fresh) { sec = t; intro_txt = ""; fresh = 0; intro = 1 }
    else if (intro) intro_txt = add(intro_txt, t)
    else pending = add(pending, t)
    next
  }
  # An indented comment continues the key above it.
  /^[[:space:]]+#/ {
    t = $0; sub(/^[[:space:]]+#[[:space:]]?/, "", t)
    if (key != "") desc = add(desc, t)
    next
  }
  /^[A-Z][A-Z0-9_]*=/ {
    flush(); open_section(); fresh = 0; intro = 0
    key = $0; sub(/=.*/, "", key)
    rest = $0; sub(/^[A-Z0-9_]+=/, "", rest)
    if (rest ~ /^"/) { val = substr(rest, 2); i = index(val, "\""); tail = substr(val, i + 1); val = substr(val, 1, i - 1) }
    else { val = rest; sub(/[[:space:]].*/, "", val); tail = substr(rest, length(val) + 1) }
    desc = pending; pending = ""
    if (match(tail, /#/)) { t = substr(tail, RSTART + 1); sub(/^[[:space:]]+/, "", t); if (t != "") desc = add(desc, t) }
    next
  }
  END { flush() }
' "${template}")"

missing="$(awk -F'\t' '$1 == "K" && $4 == "" { print $2 }' <<<"${rows}")"
if [[ -n "${missing}" ]]; then
  echo "gen-config-reference: keys with no description in ${template}:" >&2
  sed 's/^/  /' <<<"${missing}" >&2
  exit 1
fi

page="$(
  cat <<'EOF'
# Configuration keys

<!-- Generated by scripts/docs/gen-config-reference.sh from
config/config.conf.template. Edit the template comments, then rerun it. -->

Every key in `config/config.conf.template`. Copy the template to
`config/config.conf` on the dev Mac and set the values before you run
`prep-airdrop.sh`.
EOF
  awk -F'\t' '
    function esc(s) { gsub(/\|/, "\\|", s); gsub(/</, "\\&lt;", s); gsub(/>/, "\\&gt;", s); gsub(/https?:\/\/[^ )\001]+/, "`&`", s); gsub(/\001/, "<br>", s); return s }
    function head() { if (!table) printf "\n| Key | Default | Description |\n| --- | --- | --- |\n"; table = 1 }
    $1 == "S" { printf "\n## %s\n", $2; table = 0; next }
    $1 == "I" { printf "\n%s\n", esc($2); next }
    $1 == "K" {
      head(); v = ($3 == "" ? "(empty)" : "`" $3 "`")
      printf "| `%s` | %s | %s |\n", $2, v, esc($4)
    }
  ' <<<"${rows}"
)"

if ((check)); then
  current=""
  [[ -f "${output}" ]] && current="$(cat "${output}")"
  if [[ "${current}" != "${page}" ]]; then
    echo "gen-config-reference: ${output} is out of date; run scripts/docs/gen-config-reference.sh" >&2
    exit 1
  fi
  exit 0
fi

mkdir -p "$(dirname "${output}")"
printf '%s\n' "${page}" >"${output}"
